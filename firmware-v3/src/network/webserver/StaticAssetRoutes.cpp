void StaticAssetRoutes::registerRoutes(HttpRouteRegistry& registry) {

    // ── Helper: serve provisioning page (used on /provision always; on / in AP mode) ─────
    auto serveProvisioningPage = [](AsyncWebServerRequest* request) {
        char* buf = getProvisioningBuffer();
        if (!buf) {
            request->send(HttpStatus::SERVICE_UNAVAILABLE,
                          "text/plain", "Provisioning unavailable");
            return;
        }
        snprintf(buf, kProvisioningBufferSize, PROVISIONING_HTML,
                 FIRMWARE_VERSION_STRING,
                 config::NetworkConfig::MDNS_HOSTNAME);
        request->send(200, "text/html", buf);
    };

    // ── GET / ────────────────────────────────────────────────────────────
    // Mode-aware root: AP → provisioning portal, STA → fallback controller.
    // Runtime WiFi.getMode() check honours dual-mode K1 (ab8ef0ae) — no
    // compile-time WIFI_AP_ONLY gating.
    registry.onGet("/", [serveProvisioningPage](AsyncWebServerRequest* request) {
        if (WiFi.getMode() == WIFI_MODE_AP) {
            serveProvisioningPage(request);
            return;
        }
        sendFallbackController(request);
    });

    // ── GET /provision ───────────────────────────────────────────────────
    // Available in both AP and STA modes; always shows the provisioning portal
    // so users can re-join a different WiFi network without serial access.
    registry.onGet("/provision", [serveProvisioningPage](AsyncWebServerRequest* request) {
        serveProvisioningPage(request);
    });

    // ── GET /control ─────────────────────────────────────────────────────
    // Explicit direct-URL for the fallback controller, available in both modes.
    // In AP mode the user can still reach it after connecting to the K1 AP.
    registry.onGet("/control", [](AsyncWebServerRequest* request) {
        sendFallbackController(request);
    });

    // ── GET /favicon.ico ─────────────────────────────────────────────────
    registry.onGet("/favicon.ico", [](AsyncWebServerRequest* request) {
        request->send(HttpStatus::NO_CONTENT);
    });

    // ── Captive-portal detection probes ──────────────────────────────────
    // Active only while serving as Access Point (runtime check). Mobile and
    // desktop OS detectors expect canonical "success" responses on these paths;
    // returning that would suppress the portal sheet. We deliberately return
    // captive-positive shapes (302 to root or non-canonical HTML with meta
    // refresh) so iOS / Android / macOS / Firefox / Windows auto-open the
    // provisioning UI. STA-mode operation returns 404 unchanged.
    auto registerCaptiveProbe = [&registry](const char* path) {
        registry.onGet(path, [path](AsyncWebServerRequest* request) {
            if (WiFi.getMode() == WIFI_MODE_AP) {
                const auto resp = captive_portal::responseForProbePath(path);
                if (resp.action == captive_portal::ProbeAction::RedirectToRoot) {
                    request->redirect(resp.location);
                    return;
                }
                if (resp.action == captive_portal::ProbeAction::BootstrapHtml) {
                    request->send(200, resp.contentType, resp.body);
                    return;
                }
            }
            request->send(HttpStatus::NOT_FOUND);
        });
    };
    registerCaptiveProbe("/generate_204");              // Android, Chromium
    registerCaptiveProbe("/hotspot-detect.html");       // iOS, iPadOS, macOS
    registerCaptiveProbe("/library/test/success.html"); // macOS alternate
    registerCaptiveProbe("/connectivity-check.html");   // Generic detector
    registerCaptiveProbe("/canonical.html");             // Firefox detectportal
    registerCaptiveProbe("/connecttest.txt");            // Windows 10+ NCSI
    registerCaptiveProbe("/ncsi.txt");                   // Legacy Windows NCSI
    registerCaptiveProbe("/redirect");                   // Windows NCSI follow-up

    // ── 404 / onNotFound ─────────────────────────────────────────────────
    registry.onNotFound([](AsyncWebServerRequest* request) {
        // CORS preflight — pass through for all routes
        if (request->method() == HTTP_OPTIONS) {
            request->send(HttpStatus::NO_CONTENT);
            return;
        }

        // API and WebSocket paths always get a structured JSON error
        String url = request->url();
        if (url.startsWith("/api") || url.startsWith("/ws")) {
            sendErrorResponse(request, HttpStatus::NOT_FOUND,
                              ErrorCodes::NOT_FOUND, "Endpoint not found");
            return;
        }

        // AP mode: captive-portal / browser-probe fallback — redirect to /
        if (WiFi.getMode() == WIFI_MODE_AP) {
            request->redirect("/");
            return;
        }

        // STA mode: for browser-initiated HTML navigation to an unknown path,
        // serve the fallback controller so direct URL-bar typing lands on the
        // controller rather than a bare 404. API clients get a 404 above.
        const String acceptHeader = request->header("Accept");
        if (acceptHeader.indexOf("text/html") >= 0) {
            sendFallbackController(request);
            return;
        }

        request->send(HttpStatus::NOT_FOUND, "text/plain", "Not found");
    });
}

