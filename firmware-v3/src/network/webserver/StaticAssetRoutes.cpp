/**
 * @file StaticAssetRoutes.cpp
 * @brief Static HTML asset routes — fallback controller and provisioning portal.
 *
 * Serves:
 *   AP mode:  GET /        → provisioning portal (PROVISIONING_HTML snprintf)
 *             GET /provision → provisioning portal
 *             GET /control  → fallback controller (gzip PROGMEM)
 *   STA mode: GET /        → fallback controller (gzip PROGMEM)
 *             GET /provision → provisioning portal
 *             GET /control  → fallback controller (gzip PROGMEM)
 *             onNotFound HTML GET → fallback controller (SPA-style fallback)
 *
 * The fallback controller HTML is stored pre-compressed in flash as a
 * gzip byte array (FallbackControllerHtml.cpp, generated by
 * firmware-v3/scripts/gen_fallback_html.py from
 * docs/web/fallback_controller_source.html).
 * Serving it requires a single beginResponse() + addHeader() — zero SRAM copy.
 */

