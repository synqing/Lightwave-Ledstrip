// The six signal-independent colour-harmony modes (Tier 1 of the port). STM
// modes 7/8 are excluded — they consume audio signals absent from K1.
constexpr EdgeMixerMode kModes[] = {
    EdgeMixerMode::ANALOGOUS,            // 1
    EdgeMixerMode::COMPLEMENTARY,        // 2
    EdgeMixerMode::SPLIT_COMPLEMENTARY,  // 3
    EdgeMixerMode::SATURATION_VEIL,      // 4
    EdgeMixerMode::TRIADIC,              // 5
    EdgeMixerMode::TETRADIC,             // 6
};
constexpr int kNumModes = sizeof(kModes) / sizeof(kModes[0]);

constexpr uint8_t kSpreads[] = {0, 15, 30, 45, 60};
constexpr int kNumSpreads = sizeof(kSpreads) / sizeof(kSpreads[0]);

struct Probe {
    const char* name;
    uint8_t r, g, b;
    bool nearBlack;  // true when max channel < 2 (process() passes it through)
};

// 24-colour probe palette (all max(r,g,b) >= 2) + 3 near-black passthrough
