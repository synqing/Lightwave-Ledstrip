// TASK 3 — parity: the Q15.16 reference reproduces every golden within +/-1 LSB.
void test_parity_within_one_lsb(void) {
    TEST_ASSERT_GREATER_THAN_INT(0, g_goldenCount);

    int worst = 0;
    int worstMode = 0, worstSpread = 0;
    uint8_t worstIn[3] = {0, 0, 0};

    for (int i = 0; i < g_goldenCount; ++i) {
        const GoldenRow& row = g_golden[i];
        const RefMatrix M =
            refRecomputeMatrix(static_cast<EdgeMixerMode>(row.mode), row.spread);
        const CRGB in(row.in_r, row.in_g, row.in_b);
        const CRGB out = refApply(M, in);

        const int dr = absDelta(out.r, row.out_r);
        const int dg = absDelta(out.g, row.out_g);
        const int db = absDelta(out.b, row.out_b);
        const int d = (dr > dg) ? ((dr > db) ? dr : db) : ((dg > db) ? dg : db);
        if (d > worst) {
            worst = d;
            worstMode = row.mode;
            worstSpread = row.spread;
            worstIn[0] = row.in_r; worstIn[1] = row.in_g; worstIn[2] = row.in_b;
        }
    }

    // Report the tightest bound achieved (safe in pio test output).
    char msg[160];
    std::snprintf(msg, sizeof(msg),
                  "max |ref-golden| = %d LSB (mode %d spread %d in %u,%u,%u) over %d vectors",
                  worst, worstMode, worstSpread,
                  worstIn[0], worstIn[1], worstIn[2], g_goldenCount);
    std::printf("[PARITY] %s\n", msg);
    std::fflush(stdout);
    TEST_ASSERT_LESS_OR_EQUAL_INT_MESSAGE(1, worst, msg);
}

// Near-black probes (maxC < 2) must pass through process() UNCHANGED.
void test_near_black_passthrough(void) {
    int checked = 0;
    for (int i = 0; i < g_goldenCount; ++i) {
        const GoldenRow& row = g_golden[i];
        if (!row.nearBlack) continue;
        TEST_ASSERT_EQUAL_UINT8(row.in_r, row.out_r);
        TEST_ASSERT_EQUAL_UINT8(row.in_g, row.out_g);
        TEST_ASSERT_EQUAL_UINT8(row.in_b, row.out_b);
        ++checked;
    }
    // Every (mode,spread) config contributes the near-black probes.
    TEST_ASSERT_EQUAL_INT(kNumModes * kNumSpreads * kNearBlackCount, checked);
}

// TASK 4 — fault-evidence: perturb ONE reference matrix coefficient by >=2 LSB
// and prove the parity check goes RED for at least one vector; the restored
// matrix goes GREEN. A harness that cannot fail on an injected fault is
// worthless — this exercises that failure directly.
void test_fault_evidence_matrix_perturbation(void) {
    // TRIADIC / spread 0 is a clean RGB permutation (out_r = in_b, out_g = in_r,
    // out_b = in_g); the red probe (255,0,0) has a golden out_r of ~0.
    const EdgeMixerMode mode = EdgeMixerMode::TRIADIC;
    const uint8_t spread = 0;

    // Perturbation: +4 units in the source's Q8.8 matrix granularity applied to
    // one coefficient. 4 Q8.8-LSB = 4 * 256 = 1024 in Q15.16 = 0.015625 in
    // normalised matrix units. Comfortably >= the 2-LSB floor the task mandates
    // and, against a 255-valued channel, shifts the output by ~4 8-bit LSB.
    const int perturbIndex = 0;                 // out_r from in_r
    const int32_t perturbQ16 = 4 * 256;         // >= 2 LSB, unambiguous

    // Locate the golden rows for this (mode,spread).
    int worstRestored = 0;
    int worstPerturbed = 0;

    const RefMatrix restored = refMatrixFor(mode, spread, -1, 0);
    const RefMatrix broken   = refMatrixFor(mode, spread, perturbIndex, perturbQ16);

    for (int i = 0; i < g_goldenCount; ++i) {
        const GoldenRow& row = g_golden[i];
        if (row.mode != static_cast<uint8_t>(mode) || row.spread != spread) continue;

        const CRGB in(row.in_r, row.in_g, row.in_b);

        const CRGB okOut = refApply(restored, in);
        const int okD = (std::max)({absDelta(okOut.r, row.out_r),
                                    absDelta(okOut.g, row.out_g),
                                    absDelta(okOut.b, row.out_b)});
        if (okD > worstRestored) worstRestored = okD;

        const CRGB badOut = refApply(broken, in);
        const int badD = (std::max)({absDelta(badOut.r, row.out_r),
                                     absDelta(badOut.g, row.out_g),
                                     absDelta(badOut.b, row.out_b)});
        if (badD > worstPerturbed) worstPerturbed = badD;
    }

    std::printf("[FAULT] restored max delta = %d LSB (GREEN <=1), perturbed max delta = %d LSB (RED >1)\n",
                worstRestored, worstPerturbed);
    std::fflush(stdout);

    // Restored matrix: parity holds (GREEN).
    TEST_ASSERT_LESS_OR_EQUAL_INT_MESSAGE(
        1, worstRestored, "restored matrix must satisfy the +/-1 LSB parity gate");

    // Perturbed matrix: parity breaks for at least one vector (RED). If this
    // does not exceed 1 LSB, the oracle is not exercising real data — fail loud.
    TEST_ASSERT_GREATER_THAN_INT_MESSAGE(
        1, worstPerturbed,
        "injected coefficient fault MUST break parity by > 1 LSB (fault-evidence)");
}

// The golden CSV artefact was written.
void test_golden_csv_written(void) {
    TEST_ASSERT_TRUE_MESSAGE(g_csvOk, "edgemixer_golden.csv could not be opened for writing");
    TEST_ASSERT_EQUAL_INT_MESSAGE(kMaxRows, g_csvRows,
                                  "golden CSV row count must equal modes*spreads*probes");
}

int main(int, char**) {
    generateGoldensAndCsv();

    UNITY_BEGIN();
    RUN_TEST(test_golden_csv_written);
    RUN_TEST(test_near_black_passthrough);
    RUN_TEST(test_parity_within_one_lsb);
    RUN_TEST(test_fault_evidence_matrix_perturbation);
    return UNITY_END();
}
