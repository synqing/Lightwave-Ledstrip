// EdgeMixer.h uses M_PI, which is not guaranteed under strict -std=c++17 on
// some hosts (Apple libc defines __STRICT_ANSI__ and gates M_PI). Provide it
// BEFORE including the header so the header's config-time maths compiles. The
// production header is NOT modified. Guarded so a host that already supplies
// M_PI is untouched (identical value avoids any redefinition warning).
#ifndef M_PI
#define M_PI 3.14159265358979323846264338327950288
#endif

#include "effects/enhancement/EdgeMixer.h"

