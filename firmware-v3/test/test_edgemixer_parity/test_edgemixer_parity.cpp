// ============================================================================
// EdgeMixer -> K1 golden-master parity oracle (Step 0 of the port plan).
//
// Purpose (test infrastructure only; no device behaviour changes):
//   Freeze the LightwaveOS EdgeMixer colour maths as golden input->output
//   vectors by driving the REAL EdgeMixer::process(), then prove that a
//   fixed-point Q15.16 reference port (the code that will transplant to the
//   K1 SensoryBridge lineage, SQ15x16 0..1 channels) reproduces those vectors
//   within +/-1 LSB per channel. The largest port risk is silent fixed-point
//   corruption (8-bit maths on a 0..1 channel is ~256x wrong and still
//   compiles); this oracle kills that risk before any K1 code is written.
//
// Fidelity discipline:
//   - Goldens are generated by the REAL process() (never re-implemented maths).
//   - At strength 255 / UNIFORM spatial / STATIC temporal the process() path is
//     a pure direct-assign of computeTransform() for pixels with max channel
//     >= 2, and an untouched passthrough for near-black pixels (maxC < 2).
//   - The Q15.16 reference mirrors recomputeMatrix() (identical float formulae,
//     stored at FULL Q15.16 precision as K1 will) + computeTransform() (a
//     normalised-0..1 3x3 multiply, clamp, back to 8-bit).
//
// British English throughout (colour, centre, behaviour, initialise).
// Reference source: src/effects/enhancement/EdgeMixer.h (UNMODIFIED).
// ============================================================================

